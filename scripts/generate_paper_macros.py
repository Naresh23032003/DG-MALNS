"""
Generate paper/generated_macros.tex from results/tables/summary.json
(written by scripts/analyze_benchmark.py), so every number quoted in the manuscript is
taken from the raw CSVs. Macro names contain letters only, e.g.
    \\AGapLargePCMALNSMCCRIP     mean gap (%) of PC-MALNS [MC-CRIP] on Large, table A
    \\ATestOptRollbackDiff       pooled mean difference vs Opt-Rollback, table A
    \\ATestOptRollbackP          exact Wilcoxon p-value (Holm-adjusted)
    \\ATestOptRollbackWTL        wins/ties/losses
"""

import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TAB = REPO_ROOT / "results" / "tables"
OUT = REPO_ROOT / "paper" / "generated_macros.tex"
DIGITS = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]))


def key(*parts):
    s = "".join(str(p) for p in parts)
    s = "".join(DIGITS.get(ch, ch) for ch in s)
    s = s.replace("Greedy-Efficiency-Portfolio", "GEP").replace("Greedy-Gain-Portfolio", "GGP")
    return re.sub(r"[^A-Za-z]", "", s)


def num(v, nd=2):
    if v is None or v != v:
        return "--"
    return f"{v:.{nd}f}".replace("-", r"\ensuremath{-}")


def pval(p):
    return r"$<10^{-4}$" if p < 1e-4 else f"{p:.4f}"


def main():
    S = json.loads((TAB / "summary.json").read_text())
    lines = ["% Auto-generated by scripts/generate_paper_macros.py from results/tables/summary.json.",
             "% Do not edit by hand; rerun scripts/analyze_benchmark.py and this script instead.", ""]
    seen = set()

    def put(name, val):
        if name in seen:
            raise RuntimeError(f"duplicate macro {name}")
        seen.add(name)
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    def gaps(prefix, gap):
        for method, by_scale in gap.items():
            for scale, v in by_scale.items():
                put(key(prefix, "Gap", scale, method), num(v))

    def tests(prefix, t):
        for method, r in t.items():
            put(key(prefix, "Test", method, "Diff"), num(r["diff"], 3))
            if "t_lo" in r:
                put(key(prefix, "Test", method, "CI"), f"[{num(r['t_lo'], 3)}, {num(r['t_hi'], 3)}]")
            put(key(prefix, "Test", method, "WTL"), f"{r['wins']}/{r.get('ties', 0)}/{r['losses']}")
            put(key(prefix, "Test", method, "P"), pval(r["p_holm"]))

    if "A" in S:
        gaps("A", S["A"]["gap"])
        tests("A", S["A"]["tests"])
    for P, b in S.get("B", {}).items():
        gaps(f"BP{P}", b["gap"])
        tests(f"BP{P}", b["tests"])
    for label, c in S.get("C", {}).items():
        if label == "counterfactual":
            for r in c:
                reg = key("CF", r["regime"].split()[0], "Val" if "validation" in r["regime"] else "", r["rule"])
                put(reg + "Share", num(r["share_of_mccrip_gain_pct"], 1))
                put(reg + "Strict", num(r["mccrip_strictly_better_pct"], 1))
            continue
        pre = "C" + key(label.split(" (")[0])
        if "validation" in label:
            pre += "Val"
        gaps(pre, c["gap"])
        tests(pre, c["tests"])
    if "D" in S:
        gaps("D", S["D"]["gap"])
        tests("D", S["D"]["tests"])
        for m, v in S["D"]["feasible_pct"].items():
            put(key("DFeasible", m), num(v, 1))
    if "E_sweep" in S:
        for method, by_eta in S["E_sweep"].items():
            for eta, v in by_eta.items():
                put(key("ESweepGap", f"Eta{float(eta):.2f}", method), num(v))
    if "E_ablation" in S:
        for m, r in S["E_ablation"].items():
            put(key("EAbl", m, "Gap"), num(r["method_mean"]))
            put(key("EAbl", m, "Diff"), num(r["diff"], 3))
            put(key("EAbl", m, "P"), pval(r["p_holm"]))
    for r in S.get("E_scaling", []):
        put(key("EScale", r["scale"], r["mode"], "W", r["workers_W"], "Speedup"), num(r["speedup"]))
        put(key("EScale", r["scale"], r["mode"], "W", r["workers_W"], "Wall"), num(r["wall_clock_s"]))
    # totals used in the text
    cf = [r for r in S.get("C", {}).get("counterfactual", []) if "validation" not in r["regime"]]
    put("CFTotalEpochs", f"{sum({r['regime']: r['conflict_epochs'] for r in cf}.values()):,}")
    import pandas as pd
    a = pd.read_csv(REPO_ROOT / "results" / "raw" / "bench_A.csv")
    put("FallbackRuns", str(int((a[a.method == "PC-MALNS [MC-CRIP]"].matcher_fallbacks > 0).sum())))
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(seen)} macros -> {OUT}")


if __name__ == "__main__":
    sys.exit(main())
