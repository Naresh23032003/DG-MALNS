"""
paper/generated_macros.tex from results/tables/summary.json (scripts/analyze_revision3.py),
so that every number quoted in the manuscript text is computed from the raw CSVs.

Macro names: <Section><Kind><Method tag><Scale or variant>, letters only, e.g.
    \MainGapGEAll       mean gap (%) of PC-MALNS [Greedy-Efficiency], main work protocol, all 60
    \MainDiffMC         pooled difference GE - MC-CRIP (pp)        \MainWTLMC  \MainPMC (Holm)
    \SolverGapHLWXXL    HiGHS+LP-Round wall-matched, XXL, wall-clock protocol
Method tags: see TAG below; scales: Sm Me La XL XXL XXXL All.
"""

import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TAB = REPO_ROOT / "results" / "tables"
OUT = REPO_ROOT / "paper" / "generated_macros.tex"
TAG = {"PC-MALNS [Greedy-Efficiency]": "GE", "PC-MALNS [MC-CRIP]": "MC", "PC-MALNS [Quota-Surplus]": "QS",
       "PC-MALNS [Greedy-Gain]": "GG", "Opt-Rollback-Portfolio": "ORP", "Opt-SeqLock-Portfolio": "OSP",
       "Opt-Rollback": "OR", "Opt-SeqLock": "OS", "Static-Quota": "SQ", "Demand-Quota": "DQ", "LP-Round": "LPR",
       "Async-Lock": "AL", "HiGHS (1T, wall-matched)": "HW", "HiGHS (4T, wall-matched)": "HWF",
       "HiGHS+LP-Round (1T, wall-matched)": "HLW", "HiGHS (1T, CPU-matched)": "HC",
       "HiGHS+LP-Round (1T, CPU-matched)": "HLC", "HiGHS (5s)": "HFive", "HiGHS (30s)": "HThirty",
       "HiGHS (60s)": "HSixty", "HiGHS (300s)": "HThreeHundred", "HiGHS (600s)": "HSixHundred",
       "MC-CRIP": "MC", "Greedy-Efficiency": "GE", "Quota-Surplus": "QS", "Greedy-Gain": "GG"}
SCT = {"Small": "Sm", "Medium": "Me", "Large": "La", "X-Large": "XL", "XXL": "XXL", "XXXL": "XXXL", "All": "All",
       "I07-I13": "I", "INST01-20": "INST"}
DIG = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]))


def clean(s):
    s = "".join(DIG.get(ch, ch) for ch in str(s))
    return re.sub(r"[^A-Za-z]", "", s)


def tag(m):
    if m in TAG:
        return TAG[m]
    if "levels" in m:
        return "Lv" + clean(m.split("levels ")[1])
    if "prices=" in m:
        pr, qu = m.split("prices=")[1].split(", quota=")
        return "Pr" + {"none": "None", "heuristic": "Heur", "mccrip_lp": "LP"}[pr] + "Q" + qu.capitalize()
    if "restarts" in m:
        return "Restart"
    return clean(m)


def num(v, nd=2):
    if v is None or v != v:
        return "--"
    return f"{v:.{nd}f}".replace("-", r"\ensuremath{-}")


def pval(p):
    return r"\ensuremath{<10^{-4}}" if p < 1e-4 else f"{p:.4f}"


def main():
    S = json.loads((TAB / "summary.json").read_text())
    lines = ["% Auto-generated by scripts/generate_paper_macros.py from results/tables/summary.json.",
             "% Do not edit by hand.", ""]
    seen = set()

    def put(name, val):
        name = clean(name)
        if name in seen:
            raise RuntimeError(f"duplicate macro {name}")
        seen.add(name)
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    def gaps(pre, gap, nd=2):
        for m, by in gap.items():
            for s, v in by.items():
                put(pre + "Gap" + tag(m) + SCT.get(s, clean(s)), num(v, nd))

    def tests(pre, T):
        for m, r in T.items():
            t = tag(m)
            put(pre + "Diff" + t, num(r["diff"], 3))
            put(pre + "CI" + t, f"[{num(r['t_lo'], 3)}, {num(r['t_hi'], 3)}]")
            put(pre + "WTL" + t, f"{r['wins']}/{r['ties']}/{r['losses']}")
            put(pre + "Wins" + t, str(r["wins"]))
            put(pre + "Losses" + t, str(r["losses"]))
            put(pre + "P" + t, pval(r["p_holm"]))
            put(pre + "Praw" + t, pval(r["p"]))

    def bysc(pre, d, nd=1):
        for m, by in d.items():
            for s, v in by.items():
                put(pre + tag(m) + SCT.get(s, clean(s)), num(v, nd))

    if "main_work" in S:
        M = S["main_work"]
        gaps("Main", M["gap"])
        tests("Main", M["tests"])
        tests("MainOracle", M["tests_oracle"])
        bysc("MainEpochs", M["epochs"], 0)
        bysc("MainBarrierMs", M["barrier_ms"], 2)
        bysc("MainConf", M["conflict_pct"], 1)
        bysc("MainAccEpoch", M["accepted_per_epoch"], 2)
        put("MainFallbacks", str(M["mccrip_fallbacks"]))
        for r in M["per_scale_barrier_tests"]:
            p = "MainScale" + SCT[r["scale"]]
            t = tag(r["method"])
            put(p + "Diff" + t, num(r["diff"], 3))
            put(p + "WTL" + t, f"{r['wins']}/{r['ties']}/{r['losses']}")
            put(p + "P" + t, pval(r["p_holm"]))
        if M.get("counterfactual_all"):
            for r in M["counterfactual_all"]:
                put("CFAllShare" + tag(r["rule"]), num(r["share_of_mccrip_gain_pct"], 1))
                put("CFAllStrict" + tag(r["rule"]), num(r["mccrip_strictly_better_pct"], 1))
            put("CFAllEpochs", f"{M['counterfactual_all'][0]['conflict_epochs']:,}")
    if "commit" in S:
        for reg, c in S["commit"].items():
            pre = "Commit" + {"LP-Round start": "LPR", "Direct start": "Direct", "MCA-SC-Pair": "Pair"}[reg]
            gaps(pre, c["gap"], 3)
            bysc(pre + "Conf", c["conflict"], 1)
            if "tests" in c:
                tests(pre, c["tests"])
    if "counterfactual" in S:
        tot = {}
        for r in S["counterfactual"]:
            pre = "CF" + {"LP-Round start": "LPR", "Direct start": "Direct", "MCA-SC-Pair": "Pair"}[r["regime"]]
            put(pre + "Share" + tag(r["rule"]), num(r["share_of_mccrip_gain_pct"], 1))
            put(pre + "Strict" + tag(r["rule"]), num(r["mccrip_strictly_better_pct"], 1))
            tot[r["regime"]] = r["conflict_epochs"]
        put("CFTotalEpochs", f"{sum(tot.values()):,}")
    if "slack" in S:
        for x in S["slack"]:
            pre = "Slack" + ("LPR" if x["regime"].startswith("LP") else "Direct")
            for k, v in x.items():
                if k == "regime":
                    continue
                if k.endswith("_p"):
                    put(pre + clean(k.title()), pval(v))
                elif isinstance(v, int) or k == "n":
                    put(pre + clean(k.title()), str(int(v)))
                else:
                    put(pre + clean(k.title()), num(v, 3 if "acc" not in k else 2))
    if "validation" in S:
        V = S["validation"]
        gaps("Val", V["gap"], 3)
        tests("Val", V["tests"])
    for key, pre in (("levels", "Lev"), ("prices", "Price"), ("restart", "Rst")):
        if key in S:
            gaps(pre, S[key]["gap"], 3)
            tests(pre, S[key]["tests"])
            bysc(pre + "Epochs", S[key]["epochs"], 0)
    if "restart" in S:
        bysc("RstPerRun", S["restart"]["restarts_per_run"], 1)
    if "stall" in S:
        for m, v in S["stall"].items():
            t = tag(m)
            put("StallTNinetyFive" + t, num(v["t95_mean"]))
            put("StallLast" + t, num(v["last_mean"]))
            put("StallLastAll" + t, num(v["last_all_runs_mean"]))
            for s, x in v["t95_by_scale"].items():
                put("StallTNinetyFive" + t + SCT[s], num(x))
            for s, x in v["last_by_scale"].items():
                put("StallLast" + t + SCT[s], num(x))
    if "stall_wall" in S:
        put("StallWallTNinetyFive", num(S["stall_wall"]["t95_mean"]))
        put("StallWallLast", num(S["stall_wall"]["last_mean"]))
        for s, x in S["stall_wall"]["t95_by_scale"].items():
            put("StallWallTNinetyFive" + SCT[s], num(x))
    W = S["wall_main"]
    gaps("Solver", W["gap"])
    tests("Solver", W["tests"])
    bysc("WallEpochs", W["epochs"], 1)
    bysc("WallOverrun", W["overrun_pct"], 2)
    bysc("WallCpuPerWall", W["cpu_per_wall"], 2)
    for r in W["by_scale"]:
        p = "SolverScale" + SCT[r["family"]]
        t = tag(r["method"])
        put(p + "Diff" + t, num(r["diff"], 3))
        put(p + "WTL" + t, f"{r['wins']}/{r['ties']}/{r['losses']}")
        put(p + "Wins" + t, str(r["wins"]))
        put(p + "P" + t, pval(r["p_holm"]))
    for s_, v in W["ttt"].items():
        put("TttRatio" + SCT[s_], num(v["ratio_median"]))
        put("TttMedian" + SCT[s_], num(v["ttt_median"]))
        put("TttBudget" + SCT[s_], num(v["lns_wall_median"]))
        put("TttCpuRatio" + SCT[s_], num(v["ratio_cpu_median"]))
    for s_, v in W["pi"].items():
        put("PiLns" + SCT[s_], num(v["pi_lns"], 3))
        put("PiHighs" + SCT[s_], num(v["pi_highs"], 3))
    for c, by in W["async_stats"].items():
        for s_, v in by.items():
            put("Async" + clean(c.title()) + SCT[s_], num(v, 1))
    R = S["rich"]
    for J in ("20", "40"):
        pre = "Rich" + clean(J)
        gaps(pre, R[J]["gap"])
        tests(pre, R[J]["tests"])
    tests("RichPooled", R["pooled"])
    for k, v in R["ttt_combined"].items():
        J, s_ = k.split("|")
        put("RichTttRatio" + clean(J) + SCT[s_], num(v["ratio_median"], 1))
        put("RichTttCpuRatio" + clean(J) + SCT[s_], num(v["ratio_cpu_median"]))
    for which in ("original", "rerun"):
        tests("Rerun" + which.title(), R["rerun"]["tests"][which])
    put("RerunN", str(R["rerun"]["n"]))
    for k, v in R["rerun"]["epochs"].items():
        J, s_ = k.split("|")
        put("RerunEpochsOrig" + clean(J) + SCT[s_], num(v["original"], 1))
        put("RerunEpochsNew" + clean(J) + SCT[s_], num(v["rerun"], 1))
    Sw = S["sweep"]
    for eta, by in Sw["gap"].items():
        for m, v in by.items():
            put("SweepGap" + tag(m) + "Eta" + clean(f"{float(eta):.2f}"), num(v))
    for eta, by in Sw["conflict"].items():
        for m, v in by.items():
            put("SweepConf" + tag(m) + "Eta" + clean(f"{float(eta):.2f}"), num(v, 1))
    for r in Sw["tests"]:
        eta = clean(f"{float(r['family'].split('=')[1]):.2f}")
        t = tag(r["method"])
        put("SweepWTL" + t + "Eta" + eta, f"{r['wins']}/{r['ties']}/{r['losses']}")
        put("SweepPraw" + t + "Eta" + eta, pval(r["p"]))
        put("SweepP" + t + "Eta" + eta, pval(r["p_holm"]))
        put("SweepDiff" + t + "Eta" + eta, num(r["diff"], 3))
    put("SweepNTests", str(Sw["n_tests"]))
    put("SweepHolmMin", f"{min(r['p_holm'] for r in Sw['tests']):.3f}")
    for eta, v in Sw["ttt"].items():
        put("SweepTttRatioEta" + clean(f"{float(eta):.2f}"), num(v["ratio_median"]))
    Pw = S["pair_wall"]
    gaps("PairWall", Pw["gap"])
    tests("PairWall", Pw["tests"])
    for s_, v in Pw["ttt"].items():
        put("PairTttRatio" + SCT[s_], num(v["ratio_median"]))
    for s_, v in Pw["ttt"].items():
        put("PairTttCpuRatio" + SCT[s_], num(v["ratio_cpu_median"]))
    for m, v in S["run_sd"].items():
        put("RunSD" + tag(m), num(v, 3))
    Mk = S["mmkp"]
    for m, by in Mk["gap"].items():
        for s_, v in by.items():
            put("MmkpGap" + tag(m) + SCT[s_], num(v))
    tests("Mmkp", Mk["tests"])
    for m, v in Mk["feasible_pct"].items():
        put("MmkpFeas" + tag(m), num(v, 1))
    for m, v in Mk["no_improvement_share"].items():
        put("MmkpNoImp" + tag(m), num(100 * v, 0))
    put("MmkpN", str(Mk["n"]))
    put("MmkpIdentical", str(Mk["all_lns_identical"]))
    put("MmkpConfGE", num(Mk["conflict_pct"], 2))
    RC = S["run_conditions"]
    put("RCNCalib", str(RC["n_calib"]))
    put("RCBaseWall", num(RC["base_wall"], 3))
    put("RCMaxUnflagged", num(100 * RC["max_abs_drift_unflagged"], 1))
    put("RCRows", f"{RC['rows']:,}")
    put("RCNReference", str(RC["n_reference"]))
    put("RCKilled", str(len(RC["killed"])))
    put("RCKilledInstances", str(len({k["instance_name"] for k in RC["killed"]})))
    put("RCReferenceOptimal", str(RC["reference_optimal"]))
    for job in ("rich", "mmkp", "rich_rerun"):
        fl = [x for x in RC["flagged"] if x["job"] == job]
        lo = min(min(x["drift_wall"], x["drift_cpu"]) for x in fl)
        hi = max(max(x["drift_wall"], x["drift_cpu"]) for x in fl)
        put("RCDrift" + clean(job.title()) + "Lo", num(100 * lo, 0))
        put("RCDrift" + clean(job.title()) + "Hi", num(100 * hi, 0))
        put("RCDrift" + clean(job.title()) + "N", str(len(fl)))
    for w in RC["power_waits"]:
        put("RCWait" + clean(w["job"].title()), num(w["wait_s"] / 3600, 1))
    F = S["prices_fresh"]
    tests("PriceFresh", {"LP": F["tests"][F["method"]]})
    gaps("PriceFresh", F["gap"], 3)
    Sq = S["seq"]
    gaps("Seq", Sq["gap"], 3)
    for key, r in Sq["tests"].items():
        ref, m = key.split("|")
        pre = "Seq" + ("GE" if ref == "PC-MALNS [Greedy-Efficiency]" else "Seq") + "Vs" + tag(m)
        put(pre + "Diff", num(r["diff"], 3))
        put(pre + "WTL", f"{r['wins']}/{r['ties']}/{r['losses']}")
        put(pre + "Wins", str(r["wins"]))
        put(pre + "P", pval(r["p_holm"]))
        put(pre + "Praw", pval(r["p"]))
    for sc, r in Sq["per_scale"].items():
        put("SeqScale" + SCT[sc] + "WTL", f"{r['wins']}/{r['ties']}/{r['losses']}")
        put("SeqScale" + SCT[sc] + "P", pval(r["p_holm"]))
        put("SeqScale" + SCT[sc] + "Diff", num(r["diff"], 3))
    Rh = S["rho0"]
    tests("RhoZero", {"V": Rh["tests"][Rh["method"]]})
    L0 = S["level0"]
    put("LZeroTries", f"{L0['tries']:,}")
    put("LZeroDominated", str(L0["dominated"]))
    put("LZeroCommitted", str(L0["committed"]))
    put("LZeroRuns", f"{L0['runs']:,}")
    X = S["cf_all"]
    put("CFAllRuns", str(X["runs"]))
    put("CFAllIdentical", str(X["identical_to_main"]))
    for m, v in X["by_trajectory"].items():
        t = tag(m)
        put("NC" + t + "Epochs", f"{v['nonconflict_epochs']:,}")
        for r, x in v["deviate_pct"].items():
            put("NC" + t + "Dev" + tag(r), num(x, 2))
            put("NC" + t + "DevN" + tag(r), f"{v['deviate_epochs'][r]:,}")
            put("NC" + t + "Loss" + tag(r), num(v["loss_pct_of_gain"][r], 1))
        put("NC" + t + "DevMax", num(max(b["dev_pct"] for b in v["ge_by_scale"].values()), 2))
    Fb = S["fallbacks"]
    put("FallbackWorkEpochs", str(Fb["work_epochs"]))
    put("FallbackWallEpochs", str(Fb["wall_epochs"]))
    put("FallbackWallRuns", str(Fb["wall_runs"]))
    put("FallbackWallTotalRuns", f"{Fb['wall_total_runs']:,}")
    Lb = S["lb"]
    put("LBN", str(Lb["n"]))
    put("LBProvenOptimal", str(Lb["proven_optimal"]))
    put("LBFromLP", str(Lb["from_lp"]))
    for fam, v in Lb["over_lp_mean"].items():
        put("LBOverLP" + clean(fam.title()), num(v))
    for fam, v in Lb["highs_gap_median"].items():
        put("LBHighsGapMed" + clean(fam.title()), num(v))
    for fam, v in Lb["highs_gap_max"].items():
        put("LBHighsGapMax" + clean(fam.title()), num(v))
    for r in S.get("scaling", []):
        put("Scale" + clean(r["scale"]) + clean(r["mode"].title()) + "W" + clean(r["workers_W"]) + "Speedup",
            num(r["speedup"]))
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(seen)} macros -> {OUT}")


if __name__ == "__main__":
    sys.exit(main())
